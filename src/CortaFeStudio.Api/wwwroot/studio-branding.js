(function () {
  const ensureBase = ensureSubtitleTrackClient;
  ensureSubtitleTrackClient = function (project, clip) {
    const track = ensureBase(project, clip);
    if (track.autoGenerated !== false && !track.editedByUser) {
      track.enabled = false;
      track.qualityWarning = 'Primeira versão sem legendas. Ative e revise a faixa no editor antes de renderizar novamente.';
    }
    if ((track.confidence ?? 0) > 0) return track;
    const duration = Math.max(.1, clip.end - clip.start);
    const words = (project.transcript || []).flatMap(segment => segment.words || [])
      .filter(word => word.end > clip.start && word.start < clip.end);
    const timed = words.reduce((total, word) => total + Math.max(0, word.end - word.start), 0);
    const hasWordTiming = words.length >= Math.max(8, duration / 4);
    track.confidence = hasWordTiming
      ? Math.min(.98, Math.max(.78, .78 + Math.min(1, timed / duration) * .2))
      : clip.editorialProfile === 'louvor' ? .3 : .55;
    track.confidenceLabel = track.confidence >= .8 ? 'alta' : track.confidence >= .6 ? 'média' : 'baixa';
    if (track.confidence < .6 && track.autoGenerated !== false) {
      track.enabled = false;
      track.qualityWarning = 'Sem marcação precisa por palavra. A legenda foi desligada para não aparecer fora da fala.';
    }
    if (track.autoGenerated !== false && !track.editedByUser) {
      track.enabled = false;
      track.qualityWarning = 'Primeira versão sem legendas. Ative e revise a faixa no editor antes de renderizar novamente.';
    }
    return track;
  };

  const collectBase = collectSubtitleTrack;
  collectSubtitleTrack = function (card, clip) {
    const track = collectBase(card, clip), previous = clip.subtitleTrack || {};
    track.confidence = previous.confidence ?? 1;
    track.confidenceLabel = previous.confidenceLabel || 'alta';
    track.qualityWarning = previous.qualityWarning || null;
    track.autoGenerated = previous.autoGenerated ?? false;
    track.editedByUser = previous.editedByUser ?? false;
    return track;
  };

  const cardBase = clipCard;
  clipCard = function (project, clip, index) {
    const track = ensureSubtitleTrackClient(project, clip);
    const confidence = Math.round((track.confidence ?? 1) * 100);
    const badge = confidence >= 80 ? 'text-bg-success' : confidence >= 60 ? 'text-bg-warning' : 'text-bg-danger';
    const theme = clip.brandTheme || (clip.editorialProfile === 'louvor' ? 'worship' : clip.editorialProfile === 'podcast' ? 'podcast' : 'amado-jesus');
    const panel = `<details class="brand-editor mt-3" onclick="event.stopPropagation()">
      <summary>Identidade visual e segurança</summary>
      <div class="subtitle-quality mt-3"><span class="badge ${badge}">${confidence}% de confiança na legenda</span><small>${escapeHtml(track.qualityWarning || 'A faixa possui marcações suficientes para revisão.')}</small></div>
      <div class="brand-grid mt-3">
        <label class="form-check form-switch"><input class="form-check-input" name="brandFrameEnabled" type="checkbox" ${clip.brandFrameEnabled !== false ? 'checked' : ''}><span>Usar moldura Amado Jesus</span></label>
        <label>Tema<select class="form-select" name="brandTheme"><option value="amado-jesus" ${theme === 'amado-jesus' || theme === 'cortafe' ? 'selected' : ''}>Amado Jesus</option><option value="worship" ${theme === 'worship' ? 'selected' : ''}>Louvor Atmosfera</option><option value="podcast" ${theme === 'podcast' ? 'selected' : ''}>Podcast Impacto</option></select></label>
        <label class="form-check form-switch"><input class="form-check-input" name="watermarkEnabled" type="checkbox" ${clip.watermarkEnabled !== false ? 'checked' : ''}><span>Exibir marca-d’água</span></label>
        <label>Texto da marca<input class="form-control" name="watermarkText" maxlength="36" value="${escapeHtml(clip.watermarkText || 'AJ  |  AMADO JESUS')}"></label>
        <label>Transparência<input class="form-range" name="watermarkOpacity" type="range" min=".1" max="1" step=".05" value="${clip.watermarkOpacity ?? .72}"></label>
      </div>
      <small class="text-secondary">A prévia responde imediatamente. Salve e renderize para gravar a identidade no MP4.</small>
    </details>`;
    return cardBase(project, clip, index).replace('</article>', panel + '</article>');
  };

  const saveBase = saveClip;
  saveClip = async function (project, card) {
    await saveBase(project, card);
    const clip = project.clips.find(item => item.id === card.dataset.clip);
    const body = {
      brandFrameEnabled: card.querySelector('[name="brandFrameEnabled"]')?.checked ?? true,
      brandTheme: card.querySelector('[name="brandTheme"]')?.value || 'amado-jesus',
      watermarkEnabled: card.querySelector('[name="watermarkEnabled"]')?.checked ?? true,
      watermarkText: card.querySelector('[name="watermarkText"]')?.value || 'AJ  |  AMADO JESUS',
      watermarkOpacity: +(card.querySelector('[name="watermarkOpacity"]')?.value || .72)
    };
    await api(`/api/projects/${project.id}/clips/${clip.id}`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
    Object.assign(clip, body);
  };

  const selectBase = selectClip;
  selectClip = function (project, id) {
    selectBase(project, id);
    refreshBrandPreview(project.clips.find(clip => clip.id === id));
  };

  function refreshBrandPreview(clip) {
    const preview = document.querySelector('#preview');
    if (!preview || !clip) return;
    preview.querySelector('.brand-preview')?.remove();
    if (clip.videoPath || (clip.brandFrameEnabled === false && clip.watermarkEnabled === false)) return;
    const theme = clip.brandTheme || 'amado-jesus';
    preview.insertAdjacentHTML('beforeend', `<div class="brand-preview theme-${theme}">${clip.brandFrameEnabled !== false ? '<i class="brand-top"></i><i class="brand-bottom"></i>' : ''}${clip.watermarkEnabled !== false ? `<strong style="opacity:${Math.max(.1, Math.min(1, clip.watermarkOpacity ?? .82))}">${escapeHtml(clip.watermarkText || 'AJ  |  AMADO JESUS')}</strong>` : ''}</div>`);
  }

  document.addEventListener('input', event => {
    const card = event.target.closest('.clip-card');
    if (!card || !event.target.closest('.brand-editor')) return;
    const clip = current?.clips.find(item => item.id === card.dataset.clip); if (!clip) return;
    clip.brandFrameEnabled = card.querySelector('[name="brandFrameEnabled"]').checked;
    clip.brandTheme = card.querySelector('[name="brandTheme"]').value;
    clip.watermarkEnabled = card.querySelector('[name="watermarkEnabled"]').checked;
    clip.watermarkText = card.querySelector('[name="watermarkText"]').value;
    clip.watermarkOpacity = +card.querySelector('[name="watermarkOpacity"]').value;
    refreshBrandPreview(clip);
  });
  document.addEventListener('change', event => {
    if (event.target.closest('.brand-editor')) event.target.dispatchEvent(new Event('input', { bubbles: true }));
  });
})();
